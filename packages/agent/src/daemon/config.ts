import { rm } from "node:fs/promises";
import { isAbsolute } from "node:path";
import { type AgentConfig, type AgentProxyConfig, isPlainObject, shellQuote } from "@pi-web/shared";
import { AgentError } from "./errors.js";
import { readJsonFile, writeFileAtomic } from "./fsutil.js";
import type { RemotePaths } from "./paths.js";

/** Environment variable names that carry proxy settings (all removed from pi's base environment). */
export const PROXY_ENV_NAMES = [
	"HTTP_PROXY",
	"HTTPS_PROXY",
	"http_proxy",
	"https_proxy",
	"ALL_PROXY",
	"all_proxy",
	"NO_PROXY",
	"no_proxy",
] as const;

export function proxyUrl(proxy: AgentProxyConfig): string {
	return `http://pw:${encodeURIComponent(proxy.token)}@127.0.0.1:${proxy.port}`;
}

/** Proxy variables handed to pi processes when the proxy is enabled. */
export function piProxyEnv(proxy: AgentProxyConfig): Record<string, string> {
	if (!proxy.enabled) return {};
	const url = proxyUrl(proxy);
	const noProxy = proxy.noProxy.join(",");
	return {
		HTTP_PROXY: url,
		HTTPS_PROXY: url,
		http_proxy: url,
		https_proxy: url,
		NO_PROXY: noProxy,
		no_proxy: noProxy,
	};
}

/** Contents of run/proxy.env, sourced by the R/bin/pi wrapper. */
export function proxyEnvFile(proxy: AgentProxyConfig): string {
	const url = shellQuote(proxyUrl(proxy));
	const noProxy = shellQuote(proxy.noProxy.join(","));
	const lines = [
		"# Generated by pi-web-agent. Do not edit.",
		`export HTTPS_PROXY=${url}`,
		`export HTTP_PROXY=${url}`,
		`export https_proxy=${url}`,
		`export http_proxy=${url}`,
		`export ALL_PROXY=${url}`,
		`export all_proxy=${url}`,
		`export NO_PROXY=${noProxy}`,
		`export no_proxy=${noProxy}`,
	];
	return `${lines.join("\n")}\n`;
}

/** Validates the shape of an incoming AgentConfig (the host is trusted; this guards against version skew). */
export function validateAgentConfig(value: unknown): AgentConfig {
	if (!isPlainObject(value)) throw new AgentError("BAD_CONFIG", "配置格式错误");
	const c = value as Partial<AgentConfig>;
	for (const key of ["remoteRoot", "agentDir", "nodePath", "piCliPath", "companionExtPath"] as const) {
		const v = c[key];
		if (typeof v !== "string" || !isAbsolute(v)) throw new AgentError("BAD_CONFIG", `配置项 ${key} 必须是绝对路径`);
	}
	const proxy = c.proxy;
	if (!isPlainObject(proxy)) throw new AgentError("BAD_CONFIG", "配置项 proxy 缺失");
	const p = proxy as Partial<AgentProxyConfig>;
	if (p.enabled) {
		if (!Number.isInteger(p.port) || (p.port as number) < 1 || (p.port as number) > 65535) {
			throw new AgentError("BAD_CONFIG", "代理端口无效");
		}
		if (typeof p.token !== "string" || p.token.length < 8) throw new AgentError("BAD_CONFIG", "代理令牌无效");
	}
	return {
		remoteRoot: c.remoteRoot as string,
		agentDir: c.agentDir as string,
		nodePath: c.nodePath as string,
		piCliPath: c.piCliPath as string,
		piPackageDir: typeof c.piPackageDir === "string" ? c.piPackageDir : "",
		piVersion: typeof c.piVersion === "string" ? c.piVersion : "",
		companionExtPath: c.companionExtPath as string,
		proxy: {
			enabled: Boolean(p.enabled),
			port: Number(p.port) || 0,
			token: typeof p.token === "string" ? p.token : "",
			scope: p.scope === "tools" ? "tools" : "llm",
			noProxy: Array.isArray(p.noProxy) ? p.noProxy.filter((x): x is string => typeof x === "string") : [],
		},
		idleTimeoutMin: Number.isFinite(c.idleTimeoutMin) ? Math.max(0, Number(c.idleTimeoutMin)) : 30,
		extraEnv: isPlainObject(c.extraEnv)
			? Object.fromEntries(Object.entries(c.extraEnv).filter(([, v]) => typeof v === "string")) as Record<string, string>
			: {},
	};
}

/** Persists the AgentConfig (state/config.json) and maintains run/proxy.env. */
export class ConfigStore {
	private current: AgentConfig | null = null;

	constructor(private readonly paths: RemotePaths) {}

	get config(): AgentConfig | null {
		return this.current;
	}

	async load(): Promise<AgentConfig | null> {
		const raw = await readJsonFile<unknown>(this.paths.configFile);
		if (raw === undefined) return null;
		try {
			this.current = validateAgentConfig(raw);
		} catch {
			this.current = null;
		}
		return this.current;
	}

	async save(config: AgentConfig): Promise<void> {
		await writeFileAtomic(this.paths.configFile, `${JSON.stringify(config, null, "\t")}\n`, 0o600);
		this.current = config;
		await this.writeProxyEnv(config);
	}

	async writeProxyEnv(config: AgentConfig): Promise<void> {
		if (config.proxy.enabled) {
			await writeFileAtomic(this.paths.proxyEnv, proxyEnvFile(config.proxy), 0o600);
		} else {
			await rm(this.paths.proxyEnv, { force: true });
		}
	}
}
